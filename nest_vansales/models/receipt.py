# -*- coding: utf-8 -*-
from odoo import models, fields, api, _
from odoo.exceptions import UserError


class VansalesReceipt(models.Model):
    """
    Van Sales Receipt – the payment collection document.

    A receipt can allocate collected cash/card against one or more posted
    customer invoices (account.move of type out_invoice).  Payment method
    determines which journal is used from the van configuration.

    States:
        draft         – editable, not yet posted.
        pending_sync  – created offline, waiting for server-side posting.
        posted        – payment posted and (optionally) reconciled.
        cancelled     – cancelled without effect.

    TODO: implement full payment creation and reconciliation in action_post.
    """
    _name = 'vansales.receipt'
    _description = 'Van Sales Receipt'
    _rec_name = 'name'
    _order = 'date desc, id desc'

    # ── Identity ──────────────────────────────────────────────────────────────
    name = fields.Char(
        string='Receipt Reference',
        readonly=True,
        copy=False,
        default='/',
    )
    company_id = fields.Many2one(
        'res.company',
        string='Company',
        required=True,
        default=lambda self: self.env.company,
    )
    state = fields.Selection(
        selection=[
            ('draft', 'Draft'),
            ('pending_sync', 'Pending Sync'),
            ('posted', 'Posted'),
            ('cancelled', 'Cancelled'),
        ],
        string='Status',
        default='draft',
        required=True,
        tracking=True,
        index=True,
    )

    # ── Offline / PWA ─────────────────────────────────────────────────────────
    external_uid = fields.Char(
        string='External UID',
        index=True,
        copy=False,
        help='UUID generated by mobile device; used for idempotent sync.',
    )
    device_id = fields.Char(
        string='Device ID',
        copy=False,
    )

    # ── Van / User ────────────────────────────────────────────────────────────
    van_id = fields.Many2one(
        'vansales.van',
        string='Van',
        required=True,
        index=True,
    )
    user_id = fields.Many2one(
        'res.users',
        string='Salesperson',
        required=True,
        default=lambda self: self.env.user,
    )
    partner_id = fields.Many2one(
        'res.partner',
        string='Customer',
        required=True,
        index=True,
    )
    sale_order_id = fields.Many2one(
        'sale.order',
        string='Sale Order',
        index=True,
    )

    # ── Dates ─────────────────────────────────────────────────────────────────
    date = fields.Datetime(
        string='Date',
        required=True,
        default=fields.Datetime.now,
    )

    # ── Currency / amount ─────────────────────────────────────────────────────
    currency_id = fields.Many2one(
        'res.currency',
        string='Currency',
        required=True,
        default=lambda self: self.env.company.currency_id,
    )
    amount_total = fields.Monetary(
        string='Total Amount',
        currency_field='currency_id',
        compute='_compute_amount_total',
        store=True,
    )

    # ── Payment method + journal ───────────────────────────────────────────────
    payment_method = fields.Selection(
        selection=[
            ('cash', 'Cash'),
            ('bank', 'Bank Transfer'),
            ('visa', 'Visa'),
            ('mastercard', 'Mastercard'),
        ],
        string='Payment Method',
        required=True,
        default='cash',
    )
    journal_id = fields.Many2one(
        'account.journal',
        string='Journal',
        compute='_compute_journal_id',
        store=True,
        readonly=False,
        help='Resolved from van configuration based on payment method. '
             'Can be overridden manually.',
    )

    # ── Receipt lines (invoice allocations) ───────────────────────────────────
    line_ids = fields.One2many(
        'vansales.receipt.line',
        'receipt_id',
        string='Invoice Allocations',
    )

    # ── Computes ──────────────────────────────────────────────────────────────
    @api.depends('line_ids.amount_applied')
    def _compute_amount_total(self):
        for rec in self:
            rec.amount_total = sum(rec.line_ids.mapped('amount_applied'))

    @api.depends('payment_method', 'van_id')
    def _compute_journal_id(self):
        for rec in self:
            van = rec.van_id
            if not van:
                rec.journal_id = False
                continue
            method = rec.payment_method
            if method == 'cash':
                rec.journal_id = van.cash_journal_id
            elif method == 'bank':
                rec.journal_id = van.bank_journal_id
            elif method == 'visa':
                rec.journal_id = van.visa_journal_id
            elif method == 'mastercard':
                rec.journal_id = van.mastercard_journal_id
            else:
                rec.journal_id = van.cash_journal_id

