    def action_cancel(self):
        for rec in self:
            if rec.state == 'posted':
                raise UserError(_('Posted receipts cannot be cancelled directly. Please create a reversal.'))
            rec.state = 'cancelled'

    def action_reset_draft(self):
        for rec in self:
            if rec.state not in ('cancelled', 'pending_sync'):
                raise UserError(_('Only cancelled or pending-sync receipts can be reset to draft.'))
            rec.state = 'draft'

