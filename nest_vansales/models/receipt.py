class VansalesReceiptLine(models.Model):
    """
    Van Sales Receipt Line – allocation of a collected amount against an invoice.

    Each line links a posted customer invoice to the portion of the receipt
    amount that covers it.
    """
    _name = 'vansales.receipt.line'
    _description = 'Van Sales Receipt Line'

    receipt_id = fields.Many2one(
        'vansales.receipt',
        string='Receipt',
        required=True,
        ondelete='cascade',
        index=True,
    )
    invoice_id = fields.Many2one(
        'account.move',
        string='Invoice',
        required=True,
        domain=[
            ('move_type', '=', 'out_invoice'),
            ('state', '=', 'posted'),
        ],
        help='Posted customer invoice being (partially) paid by this receipt.',
    )
    invoice_amount_residual = fields.Monetary(
        string='Invoice Balance',
        related='invoice_id.amount_residual',
        currency_field='currency_id',
        readonly=True,
    )
    currency_id = fields.Many2one(
        related='receipt_id.currency_id',
        store=True,
    )
    amount_applied = fields.Monetary(
        string='Amount Applied',
        required=True,
        currency_field='currency_id',
        help='Amount from this receipt allocated to this invoice.',
    )
